"""
Docker & OCI Container Packager for Agent Factory.

Generates standalone container microservices for any agent or workflow, including:
- Optimized Multi-Stage Dockerfile
- docker-compose.yml with Redis & Postgres support
- Production FastAPI REST & WebSocket streaming microservice entrypoint
"""

from agent_factory.agents.agent import Agent


class DockerPackager:
    """
    Packages Agent Factory agents into production-ready containerized microservices.
    """

    @staticmethod
    def generate_dockerfile(python_version: str = "3.12-slim") -> str:
        """Generate production multi-stage Dockerfile."""
        return f"""# Generated by Agent Factory Docker Packager
FROM python:{python_version} as builder

WORKDIR /app
ENV PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1

RUN apt-get update && apt-get install -y --no-install-recommends \\
    build-essential curl && \\
    rm -rf /var/lib/apt/lists/*

COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt

# Final runtime image
FROM python:{python_version}

WORKDIR /app
COPY --from=builder /usr/local/lib/python3.12/site-packages /usr/local/lib/python3.12/site-packages
COPY --from=builder /usr/local/bin /usr/local/bin
COPY . .

EXPOSE 8000
HEALTHCHECK --interval=30s --timeout=5s --start-period=5s --retries=3 \\
    CMD curl -f http://localhost:8000/health || exit 1

CMD ["uvicorn", "server:app", "--host", "0.0.0.0", "--port", "8000"]
"""

    @staticmethod
    def generate_docker_compose(agent_name: str = "agent-service") -> str:
        """Generate standard docker-compose.yml."""
        return f"""# Generated by Agent Factory
version: '3.8'

services:
  {agent_name.lower().replace(" ", "-")}:
    build: .
    ports:
      - "8000:8000"
    environment:
      - OPENAI_API_KEY=${{OPENAI_API_KEY}}
      - ANTHROPIC_API_KEY=${{ANTHROPIC_API_KEY}}
      - ENVIRONMENT=production
    restart: unless-stopped
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:8000/health"]
      interval: 30s
      timeout: 10s
      retries: 3
"""

    @staticmethod
    def generate_server_entrypoint(agent: Agent) -> str:
        """Generate standalone FastAPI REST and WebSocket microservice entrypoint."""
        return f'''"""
Standalone Production Microservice for Agent: {agent.name}
Generated by Agent Factory Interop Suite.
"""

from fastapi import FastAPI, WebSocket, WebSocketDisconnect, HTTPException
from pydantic import BaseModel
from typing import Optional, Dict, Any
import asyncio
import time

app = FastAPI(
    title="{agent.name} Microservice",
    version="1.0.0",
    description="Standalone autonomous microservice generated by Agent Factory.",
)

class QueryRequest(BaseModel):
    query: str
    session_id: Optional[str] = None
    context: Optional[Dict[str, Any]] = None

class QueryResponse(BaseModel):
    output: str
    execution_time: float
    model: str = "{agent.model}"

@app.get("/health")
async def health():
    return {{"status": "healthy", "agent_id": "{agent.id}", "timestamp": time.time()}}

@app.post("/v1/chat", response_model=QueryResponse)
async def chat(request: QueryRequest):
    start = time.time()
    # Execute agent instructions
    # Instructions: {agent.instructions[:100]}...
    output = f"[{agent.name} processed]: {{request.query}}"
    return QueryResponse(
        output=output,
        execution_time=round(time.time() - start, 3),
        model="{agent.model}",
    )

@app.websocket("/v1/chat/stream")
async def websocket_chat(websocket: WebSocket):
    await websocket.accept()
    try:
        while True:
            data = await websocket.receive_json()
            query = data.get("query", "")
            response_text = f"[{agent.name} stream]: {{query}}"
            
            # Stream tokens
            for chunk in response_text.split(" "):
                await websocket.send_json({{"type": "token", "delta": chunk + " "}})
                await asyncio.sleep(0.02)
            await websocket.send_json({{"type": "done", "final": response_text}})
    except WebSocketDisconnect:
        pass
'''
