        "\n",
        "class AgentTracer:\n",
        "    \"\"\"Production tracer with hierarchical spans, token cost calculation, and ASCII tree visualizer.\"\"\"\n",
        "    \n",
        "    # Pricing per 1K tokens ($ in / $ out)\n",
        "    MODEL_PRICING = {\n",
        "        'gpt-4o': (0.005, 0.015),\n",
        "        'gpt-4o-mini': (0.00015, 0.0006),\n",
        "        'claude-3-5-sonnet': (0.003, 0.015)\n",
        "    }\n",
        "    \n",
        "    def __init__(self, trace_name: str):\n",
        "        self.trace_id = str(uuid.uuid4())[:8]\n",
        "        self.trace_name = trace_name\n",
        "        self.spans: List[Span] = []\n",
        "        self._active_stack: List[str] = []\n",
        "        \n",
        "    def start_span(self, name: str, **metadata) -> Span:\n",
        "        parent_id = self._active_stack[-1] if self._active_stack else None\n",
        "        span = Span(span_id=str(uuid.uuid4())[:6], name=name, parent_id=parent_id, metadata=metadata)\n",
        "        self.spans.append(span)\n",
        "        self._active_stack.append(span.span_id)\n",
        "        return span\n",
        "        \n",
        "    def end_span(self, span: Span, tokens_in: int = 0, tokens_out: int = 0, model: str = 'gpt-4o', status: str = 'OK'):\n",
        "        span.end_time = time.time()\n",
        "        span.duration_ms = round((span.end_time - span.start_time) * 1000, 2)\n",
