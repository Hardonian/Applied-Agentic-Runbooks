        "# ==============================================================================\n",
        "# CELL 13: PRODUCTION PROMETHEUS METRICS\n",
        "# ==============================================================================\n",
        "import time\n",
        "from typing import Dict, Any\n",
        "\n",
        "class AgentMetricsCollector:\n",
        "    \"\"\"Production telemetry collector supporting Prometheus exposition format.\"\"\"\n",
        "    def __init__(self):\n",
        "        self.requests_total: Dict[str, int] = {}\n",
        "        self.tokens_total: Dict[str, int] = {}\n",
        "        self.duration_seconds: Dict[str, List[float]] = {}\n",
        "        self.errors_total: Dict[str, int] = {}\n",
        "        \n",
        "    def record_request(self, agent_name: str, model: str, duration_sec: float, tokens: int, status: str = 'success'):\n",
        "        key = f'{agent_name}|{model}|{status}'\n",
        "        self.requests_total[key] = self.requests_total.get(key, 0) + 1\n",
        "        \n",
        "        tok_key = f'{agent_name}|{model}'\n",
        "        self.tokens_total[tok_key] = self.tokens_total.get(tok_key, 0) + tokens\n",
        "        \n",
        "        if agent_name not in self.duration_seconds:\n",
        "            self.duration_seconds[agent_name] = []\n",
        "        self.duration_seconds[agent_name].append(duration_sec)\n",
        "        \n",
        "        if status != 'success':\n",
        "            err_key = f'{agent_name}|{status}'\n",
        "            self.errors_total[err_key] = self.errors_total.get(err_key, 0) + 1\n",
        "\n",
        "    def generate_prometheus_exposition(self) -> str:\n",
        "        \"\"\"Generate standard text format metrics for Prometheus scrapers.\"\"\"\n",
        "        lines = [\n",
        "            \"# HELP agent_requests_total Total number of agent execution requests\",\n",
        "            \"# TYPE agent_requests_total counter\"\n",
        "        ]\n",
        "        for key, count in self.requests_total.items():\n",
        "            agent, model, status = key.split('|')\n",
        "            lines.append(f'agent_requests_total{{agent=\"{agent}\",model=\"{model}\",status=\"{status}\"}} {count}')\n",
        "            \n",
        "        lines.extend([\n",
        "            \"# HELP agent_tokens_consumed_total Total LLM tokens consumed\",\n",
        "            \"# TYPE agent_tokens_consumed_total counter\"\n",
        "        ])\n",
        "        for key, tokens in self.tokens_total.items():\n",
        "            agent, model = key.split('|')\n",
        "            lines.append(f'agent_tokens_consumed_total{{agent=\"{agent}\",model=\"{model}\"}} {tokens}')\n",
        "            \n",
        "        lines.extend([\n",
        "            \"# HELP agent_latency_seconds_avg Average request duration in seconds\",\n",
        "            \"# TYPE agent_latency_seconds_avg gauge\"\n",
        "        ])\n",
        "        for agent, durs in self.duration_seconds.items():\n",
        "            avg_dur = sum(durs) / len(durs) if durs else 0.0\n",
        "            lines.append(f'agent_latency_seconds_avg{{agent=\"{agent}\"}} {avg_dur:.4f}')\n",
        "            \n",
        "        return \"\\n\".join(lines)\n",
        "\n",
